/* V8.94 – graphical time-scaled research interface and canonical chronology */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('index.html');
const script=read('v894-research-gantt.js');
const css=read('v894-research-gantt.css');
const dataOld=read('data/church-shifts.v892.js');
const dataNew=read('data/research-chronology.v894.js');
for(const p of ['v894-research-gantt.js','v894-research-gantt.css','data/research-chronology.v894.js'])assert.ok(html.includes(p),'Missing dependency '+p);
assert.ok(html.indexOf('v893-research-hub.js')<html.indexOf('v894-research-gantt.js'),'Research hub must load before native graph');
assert.ok(html.indexOf('data/research-chronology.v894.js')<html.indexOf('v894-research-gantt.js'),'Timeline data must load first');
for(const s of [script,dataNew])assert.doesNotThrow(()=>new vm.Script(s));
const window={};
vm.runInNewContext(dataOld,{window});
vm.runInNewContext(dataNew,{window});
const historic=window.TIDENS_CHURCH_SHIFTS.events;
const questions=window.TIDENS_BIG_QUESTIONS_TIMELINE.events;
assert.equal(historic.length,67);
assert.equal(questions.length,25);
assert.equal(new Set([...historic,...questions].map(x=>x.id)).size,92);
assert.ok(questions.some(x=>x.precision==='approx'));
assert.ok(questions.some(x=>x.precision==='range'));
assert.ok(questions.every(x=>Number.isFinite(x.year)&&x.year>=-1000&&x.year<=2026));
assert.ok(questions.every(x=>x.source.startsWith('https://')&&x.certainty&&x.detail.length>125));
const seenLeibniz=questions.filter(x=>x.year===1710);
assert.equal(seenLeibniz.length,1,'Leibniz 1710 must have only one canonical ID');
assert.ok(['good','will'].every(x=>seenLeibniz[0].topics.includes(x)));
assert.ok(questions.filter(x=>x.topics.includes('afterlife')).length>=10);
assert.ok(questions.filter(x=>x.topics.includes('good')).length>=8);
assert.ok(questions.filter(x=>x.topics.includes('will')).length>=7);
assert.ok(css.includes('v828-gantt')&&css.includes('max-width:690px'),'Native visual language and responsive rules are required');
const hub={innerHTML:''},handlers={},winEvents={};
const root={addEventListener(type,handler){handlers[type]=handler}};
const document={readyState:'complete',getElementById(id){if(id==='researchView')return root;if(id==='tvResearchGraph')return hub;return null}};
window.TidensResearchHub={getSelected:()=>window.currentTopic||'afterlife'};
window.addEventListener=(type,handler)=>{winEvents[type]=handler};
vm.runInNewContext(script,{window,document});
assert.ok(window.TidensResearchGraphV894,'Graph API missing');
assert.match(hub.innerHTML,/v828-gantt-row/,'Graph must use main Gantt row classes');
assert.match(hub.innerHTML,/v894-axis-ticks/,'Graph must display a proportional time scale');
assert.match(hub.innerHTML,/Henoktraditionens Väktarbok/,'Afterlife events must render');
assert.doesNotMatch(hub.innerHTML,/Rowes evidentiella/,'Do not mix unrelated areas');
const first=questions.find(x=>x.topics.includes('afterlife'));
assert.equal(window.TidensResearchGraphV894.selectEvent(first.id),true);
assert.match(hub.innerHTML,/v894SelectedEvent/);
assert.match(hub.innerHTML,/Händelsens betydelse|Vad hände/);
assert.match(hub.innerHTML,/source|källan/i);
assert.equal(window.TidensResearchGraphV894.setRange('modern'),true);
assert.doesNotMatch(hub.innerHTML,/ca 250 f.Kr. · Henoktraditionens Väktarbok/);
window.currentTopic='women';winEvents['tvhub:select']();
assert.match(hub.innerHTML,/kvinnliga präster/,'New church theme must appear with same graphical design');
window.currentTopic='good';winEvents['tvhub:select']();
assert.match(hub.innerHTML,/Leibniz/,'Older God goodness theme must have dated events');
assert.doesNotMatch(hub.innerHTML,/Galilei döms/);
window.currentTopic='overview';winEvents['tvhub:select']();
assert.equal(hub.innerHTML,'','No full chronological graph on library overview');
console.log('V8.94 PASS – 92 distinct time points, all themes share native Gantt marks, bibliography, era precision, zoom and mobile styling.');
