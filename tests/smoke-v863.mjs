import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const ctx={window:{}};
vm.runInNewContext(read('data/bible-books-v857.js'),ctx);
assert.equal(ctx.window.TIDENS_BIBLE_BOOKS.length,66);
const v=ctx.window.TIDENS_BIBLE_VARIANTS.B002;
assert.equal(v.length,1);
assert.ok(v[0].witness.includes('4Q22'));
assert.ok(v[0].limits.includes('datering')||v[0].limits.includes('datum'));
assert.ok(v[0].sources.length>=2);
const reader=read('v858-book-reader.js');
assert.ok(reader.includes('Konkreta textvarianter'));
assert.ok(reader.includes('TIDENS_BIBLE_VARIANTS'));
vm.runInNewContext(read('data/review-ledger.js'),ctx);
vm.runInNewContext(read('data/c6-progress.js'),ctx);
const l=ctx.window.TIDENS_REVIEW_LEDGER;
const n=Object.values(l.claimChecks).reduce((x,y)=>x+y.length,0);
assert.ok(n>=41);
assert.equal(ctx.window.TIDENS_C6_PROGRESS.history.at(-1).claimChecks,n);
assert.equal(Object.keys(l.completePostReviews).length,0);
console.log('OK V8.63: Exodus variant documented, 41 checks, no completed reviews');
