import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const ctx={window:{}};
vm.runInNewContext(read('data/bible-books-v857.js'),ctx);
const dossier=ctx.window.TIDENS_TORAH_TEXT_HISTORY;
assert.ok(dossier&&dossier.witnesses.length===4);
assert.ok(dossier.sources.length>=2);
assert.ok(/kopior/.test(dossier.limits));
assert.equal(ctx.window.TIDENS_BIBLE_BOOKS.length,66);
const reader=read('v858-book-reader.js');
assert.ok(reader.includes('Handskrifter och textöverföring'));
assert.ok(reader.includes("B00[1-5]"));
vm.runInNewContext(read('data/review-ledger.js'),ctx);
vm.runInNewContext(read('data/c6-progress.js'),ctx);
const ledger=ctx.window.TIDENS_REVIEW_LEDGER;
const checks=Object.values(ledger.claimChecks);
const n=checks.reduce((a,b)=>a+b.length,0);
assert.ok(n>=40);
assert.ok(Object.keys(ledger.claimChecks).length>=17);
assert.equal(ctx.window.TIDENS_C6_PROGRESS.history.at(-1).claimChecks,n);
assert.equal(Object.keys(ledger.completePostReviews).length,0);
assert.ok(ledger.claimChecks.H019.some(x=>x.claim.includes('4QpaleoExod')));
console.log('V8.62 OK: four textual witness classes, 66 books, 40 C6 checks, 0 completed');
