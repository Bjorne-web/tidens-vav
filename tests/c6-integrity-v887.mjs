import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx={window:{}};vm.createContext(ctx);
for(const file of ['data/c6-progress.js','data/review-ledger.js'])vm.runInContext(fs.readFileSync(file,'utf8'),ctx,{filename:file});
const p=ctx.window.TIDENS_C6_PROGRESS,l=ctx.window.TIDENS_REVIEW_LEDGER;
const count=a=>new Set(a||[]).size;
assert.equal(p.total,p.research+p.original,'Inventory must reconcile');
for(const key of ['partialReportIds','proposedCorrectionIds','implementedCorrectionIds'])assert.equal(count(p[key]),p[key].length,'Duplicate IDs: '+key);
for(const id of p.implementedCorrectionIds)assert.ok(p.proposedCorrectionIds.includes(id),'Implemented correction missing proposal: '+id);
assert.ok(Object.keys(l.completePostReviews||{}).length===0,'Full reviews cannot be silently inferred');
const checks=Object.entries(l.claimChecks||{}).reduce((n,[id,arr])=>{assert.match(id,/^[HOB][0-9]{3}$/);assert.ok(Array.isArray(arr));return n+arr.length},0);
const history=p.history||[];assert.ok(history.length,'History required');
const latest=history.at(-1);
assert.equal(latest.inventory,p.total);
assert.equal(latest.partialReports,count(p.partialReportIds));
assert.equal(latest.proposedCorrections,count(p.proposedCorrectionIds));
assert.equal(latest.implementedCorrections,count(p.implementedCorrectionIds));
assert.equal(latest.wholeApproved,0);
assert.ok(checks>=latest.claimChecks,'Historical reported claim count exceeds available ledger');
console.log(JSON.stringify({inventory:p.total,partialReports:latest.partialReports,implementedCorrections:latest.implementedCorrections,documentedClaims:checks,fullReviews:0,status:'C6 consistency verified; no scientific content newly approved'},null,2));
