import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('index.html');
assert.ok(html.includes('Version 8.78 · upptäck, jämför och granska källorna'));
assert.ok(html.includes('Bygge v8.78-c6-20261015'));
assert.ok(!html.includes('Version 8.69'));
const ctx={window:{}};
for(const p of ['data/review-ledger.js','data/c6-progress.js','data/bible-books-v857.js'])vm.runInNewContext(read(p),ctx);
const ledger=ctx.window.TIDENS_REVIEW_LEDGER;
const progress=ctx.window.TIDENS_C6_PROGRESS.history.at(-1);
const n=Object.values(ledger.claimChecks).reduce((a,b)=>a+b.length,0);
assert.ok(n>=77);
assert.ok(Object.keys(ledger.claimChecks).length>=35);
assert.equal(progress.claimChecks,n);
assert.equal(progress.claimCheckPosts,Object.keys(ledger.claimChecks).length);
for(const id of ['H038','H039','H044'])assert.ok(ledger.claimChecks[id][0].sourceUrl.startsWith('https://'));
assert.equal(ctx.window.TIDENS_BIBLE_BOOK_RESEARCH.B028.status,'delgranskad');
assert.equal(ctx.window.TIDENS_BIBLE_BOOKS.length,66);
assert.equal(Object.keys(ledger.completePostReviews).length,0);
console.log('V8.70 OK: version marker, 77 C6 claims in 35 posts, Hosea');
