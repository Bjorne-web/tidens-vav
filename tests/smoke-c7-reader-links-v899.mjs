// C7 v899: link generation, display invariants and shared bibliography UI.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
execFileSync(process.execPath,['--check',new URL('../v899-c7-reader-links.js',import.meta.url).pathname]);
const sandbox={window:{}};vm.runInNewContext(read('v899-c7-reader-links.js'),sandbox);
const url=text=>sandbox.window.TidensC7Ui.references(text).map(x=>x.url);
assert.equal(url('Judas 14–15')[0],'https://www.bible.com/sv/bible/1223/JUD.1.SFB15');
assert.equal(sandbox.window.TidensC7Ui.references('Judas 14–15')[0].label,'Judas 14–15');
assert.equal(sandbox.window.TidensC7Ui.references('2 Mos 21–23')[0].label,'2 Mos 21–23');
assert.equal(url('Mark 16:9–20')[0],'https://www.bible.com/sv/bible/1223/MRK.16.SFB15');
assert.equal(url('2 Mos 21–23')[0],'https://www.bible.com/sv/bible/1223/EXO.21.SFB15');
assert.equal(url('1 Tim 2:11–15')[0],'https://www.bible.com/sv/bible/1223/1TI.2.SFB15');
assert.equal(url('Rom 1:26–27')[0],'https://www.bible.com/sv/bible/1223/ROM.1.SFB15');
assert.equal(url('Gen 6–9')[0],'https://www.bible.com/sv/bible/1223/GEN.6.SFB15');
assert.equal(url('2 Joh 4')[0],'https://www.bible.com/sv/bible/1223/2JN.1.SFB15');
assert.equal(url('Ps 82:1–6')[0],'https://www.bible.com/sv/bible/1223/PSA.82.SFB15');
assert.equal(url('Judas 14–15 och Mark 16:9–20').length,2);
assert.equal(url('1 Henok 1:9').length,0,'Enoch is not SFB15 canonical Bible book');
const html=read('index.html');
const jsPos=html.indexOf('<script src="v899-c7-reader-links.js"></script>');
assert.ok(jsPos>0&&jsPos<html.indexOf('<script src="v838-reader-reflow.js">'));
assert.ok(jsPos<html.indexOf('<script src="v839-reader-unified.js">'));
assert.ok(jsPos<html.indexOf('<script src="v858-book-reader.js">'));
assert.ok(html.includes('<link rel="stylesheet" href="v899-c7-reader-links.css">'));
const book=read('v858-book-reader.js');
assert.match(book,/v838-faith-impact v839-faith-context/,'Bibles and histories use same styled significance card');
assert.match(book,/window.TidensC7Ui\?\.decorate\(article\)/,'Books must link Bible references');
assert.match(read('v839-reader-unified.js'),/window.TidensC7Ui\?\.decorate\(article\)/);
assert.match(read('v838-reader-reflow.js'),/window.TidensC7Ui\?\.decorate\(article\)/);
const css=read('v899-c7-reader-links.css');
assert.ok(css.includes('tv-c7-bible-ref')&&css.includes('tv-book-reader'));
const datasets=Array.from({length:9},(_,i)=>read('data/c7-religionshistorisk-betydelse.v'+(890+i)+'.js'));
const urls=datasets.flatMap(source=>[...source.matchAll(/https?:\/\/[^\s"'<>]+/g)].map(m=>m[0]));
assert.ok(urls.length>=250,'Keep all historical and biblical C7 sources, do not delete broken links');
assert.ok(urls.some(u=>u.includes('academic.oup.com')),'Keep named research sources');
assert.ok(read('v899-c7-reader-links.js').includes('Sök publikationen'),'Add alternative when scholarly site restricts access');
console.log('C7 v899 OK: shared blue card, Bible chapter links, 261+ bibliography URLs retained and fallback.');
