/* V8.93 – library consolidation and research depth regression */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const page=read('index.html'),hubScript=read('v893-research-hub.js'),css=read('v893-research-hub.css'),longformScript=read('data/church-longform.v893.js'),dataSource=read('data/church-shifts.v892.js');
for(const path of ['v893-research-hub.js','v893-research-hub.css','data/church-longform.v893.js'])assert.ok(page.includes(path),'Missing asset '+path);
assert.ok(page.indexOf('data/church-longform.v893.js')<page.indexOf('v892-church-shifts.js'),'Longform source must load before renderer');
assert.ok(page.indexOf('v893-research-hub.js')>page.indexOf('v892-church-shifts.js'),'Library hub must initialize last');
for(const s of [hubScript,longformScript])assert.doesNotThrow(()=>new vm.Script(s));
const window={};vm.runInNewContext(dataSource,{window});vm.runInNewContext(longformScript,{window});
const data=window.TIDENS_CHURCH_SHIFTS,large=window.TIDENS_CHURCH_LONGFORM;
assert.equal(data.events.length,61);
assert.equal(data.topics.length,12);
assert.equal(Object.keys(large).length,11);
for(const t of data.topics){
 assert.ok(data.events.filter(x=>x.topic===t.id).length>=3,'Too sparse: '+t.id);
 if(t.id==='sexuality')continue;
 const work=large[t.id];assert.ok(work,'No research content: '+t.id);
 assert.ok(work.lead.length>70);
 assert.ok(work.sections.length>=3,'Too few chapters: '+t.id);
 assert.ok(work.sections.every(x=>x.paragraphs.length>=2),'Section not developed: '+t.id);
 assert.ok(work.sections.flatMap(x=>x.paragraphs).join(' ').length>1350,'Insufficient substantive depth: '+t.id);
 assert.ok(work.sections.every(x=>x.sources.every(s=>s[1].startsWith('https://'))),'Missing source URLs: '+t.id);
}
assert.equal(Object.values(large).flatMap(x=>x.sections).flatMap(x=>x.paragraphs).length,66);
const refLabels=Object.values(large).flatMap(x=>x.sections).flatMap(x=>x.paragraphs).flatMap(p=>[...p.matchAll(/\[\[([^\]]+)\]\]/g)].map(m=>m[1]));
assert.ok(refLabels.length>=25,'Few Bible passage links');
assert.ok(css.includes('.tvhub-card')&&css.includes('max-width:620px'),'Missing responsive hub');
const nodes=['tvChurchShifts','v890Nav','v888Track','v889-good','v889-will','v890Bridge','someLegacyRecords'].map(id=>({id,hidden:false,classList:{add(){},toggle(){}}}));
const host={children:nodes,firstElementChild:nodes[0],querySelector(selector){return this.children.find(x=>'#'+x.id===selector)||null},insertBefore(el,anchor){this.children.splice(this.children.indexOf(anchor),0,el)},addEventListener(){}};
const document={readyState:'complete',getElementById(id){if(id==='researchView')return host;return nodes.find(x=>x.id===id)||null},createElement(tag){return{id:'',tag,innerHTML:'',className:'',hidden:false,classList:{add(){},toggle(){}},scrollIntoView(){}}}};
class Observer{observe(){}};
let fromTimeline=null;
window.TidensChurchShiftsV1={selectTopic(x){fromTimeline=x}};
const context={window,document,MutationObserver:Observer};
vm.runInNewContext(hubScript,context);
const hub=window.TidensResearchHub;
assert.ok(hub,'Hub not initialized');
assert.equal(hub.getSelected(),'overview');
assert.equal(hub.getTopics().length,16,'Old and new research tracks must appear in single library');
assert.ok(nodes.find(x=>x.id==='tvResearchHub').innerHTML.includes('Himmel, helvete och livet efter döden'));
assert.ok(nodes.find(x=>x.id==='tvResearchHub').innerHTML.includes('Samkönade relationer'));
assert.ok(nodes.find(x=>x.id==='tvResearchHub').innerHTML.includes('Är Gud god?'));
assert.ok(nodes.find(x=>x.id==='tvResearchHub').innerHTML.includes('Den fria viljan'));
assert.equal(nodes.find(x=>x.id==='v888Track').hidden,true,'Overview should not show all long research panels');
assert.equal(hub.select('afterlife',false),true);
assert.equal(nodes.find(x=>x.id==='v888Track').hidden,false);
assert.equal(nodes.find(x=>x.id==='tvChurchShifts').hidden,true);
assert.equal(hub.select('women',false),true);
assert.equal(fromTimeline,'women');
assert.equal(nodes.find(x=>x.id==='tvChurchShifts').hidden,false);
assert.equal(nodes.find(x=>x.id==='v888Track').hidden,true);
assert.equal(hub.select('legacy',false),true);
assert.equal(nodes.find(x=>x.id==='someLegacyRecords').hidden,false,'Legacy material must remain reachable');
assert.equal(hub.select('unknown',false),false);
console.log('V8.93 PASS – 16 consolidated research entries, 61 events, 66 longform paragraphs, accessible legacy materials, isolated active panels.');
