import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const ctx={window:{}};
vm.runInNewContext(read('data/review-ledger.js'),ctx);
vm.runInNewContext(read('data/c6-progress.js'),ctx);
const claims=ctx.window.TIDENS_REVIEW_LEDGER.claimChecks;
const latest=ctx.window.TIDENS_C6_PROGRESS.history.at(-1);
const count=Object.values(claims).reduce((n,a)=>n+a.length,0);
assert.equal(count,59);
assert.equal(latest.claimChecks,count);
assert.equal(latest.claimCheckPosts,20);
assert.equal(Object.keys(ctx.window.TIDENS_REVIEW_LEDGER.completePostReviews).length,0);
const added=Object.values(claims).flat().filter(x=>x.verified==='2026-10-14'&&x.passage);
assert.equal(added.length,10);
assert.equal(claims.H020.filter(x=>x.passage).length,4);
assert.equal(claims.H019.filter(x=>x.passage).length,6);
assert.ok(added.every(x=>/^https:\/\//.test(x.sourceUrl)&&x.limit.length>40&&x.scope.length>30&&x.timeClarification.length>80));
assert.equal(new Set(added.filter(x=>x.passage).map(x=>x.passage)).size,10);
console.log('OK V8.64: 10 new passage-specific checks, 51 total, 0 full scientific sign-offs');
