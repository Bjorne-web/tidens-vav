/* Research 2 V8.91: bibliography, depth and direct scripture links */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=read('index.html');
const text=read('v891-expanded-research.js');
const css=read('v891-expanded-research.css');
assert.ok(html.includes('v891-expanded-research.js')&&html.includes('v891-expanded-research.css'),'Missing loaded content assets');
assert.doesNotThrow(()=>new vm.Script(text),'JavaScript syntax failed');
assert.ok(text.length>26000,'Expanded scholarship unexpectedly short');
assert.ok(text.includes('Matthew Suriano') && text.includes('The Problem of Evil') && text.includes('Foreknowledge and Free Will'));
assert.ok(css.includes('max-width:720px') && css.includes('v891-verse'),'Mobile layout or links absent');
const window={};const hooks=[];
const document={readyState:'loading',addEventListener:(type,cb)=>hooks.push([type,cb])};
vm.runInNewContext(text,{document,window,NodeFilter:undefined,MutationObserver:class{}});
assert.equal(typeof window.TidensReview2BibleLink,'function');
const link=window.TidensReview2BibleLink;
assert.match(link('Matt 25:46'),/https:\/\/www\.bible\.com\/sv\/bible\/154\/MAT\.25\.46\.B2000/);
assert.match(link('Rom 9:14–24'),/\/ROM\.9\.14\.B2000/);
assert.match(link('Dan 12:2'),/\/DAN\.12\.2\.B2000/);
assert.match(link('2 Mack 7:9–14'),/\/417\/2MA\.7\.B2000D/);
assert.match(link('1 Kor 15:22–28'),/\/1CO\.15\.22\.B2000/);
assert.match(link('Jona 4:1–11'),/\/JON\.4\.1\.B2000/);
assert.match(link('Job 38–42'),/\/JOB\.38\.B2000/);
assert.ok(link('1 Henok 22').includes('en.wikisource.org/wiki/'), 'Provide external text link for 1 Henok');
const refLabels=[...text.matchAll(/\[\[([^\]]+)\]\]/g)].map(m=>m[1]);
const actualRefs=refLabels.filter(ref=>ref.length<45&&!ref.includes('https:')&&!ref.includes("'"));
assert.ok(actualRefs.length>=40,'Too few linked scriptural references');
for(const r of actualRefs) assert.ok(link(r).includes('href='),'Unmapped scripture: '+r);
const sections=[...text.matchAll(/title:'(\d+)\. /g)].length;
assert.equal(sections,16,'Expected four deep sections for each of four research themes');
assert.ok(text.includes('Fördjupad, källorienterad genomgång'));
console.log('Granskning 2 V8.91 PASS – '+sections+' in-depth sections; '+refLabels.length+' Bible references, Bibel 2000 deep links and accessible reading styles.');
