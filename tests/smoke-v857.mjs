import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const ctx={window:{}};
vm.runInNewContext(read('data/bible-books-v857.js'),ctx);
const bs=Array.from(ctx.window.TIDENS_BIBLE_BOOKS);
assert.equal(bs.length,66);
assert.equal(bs.filter(x=>x.testament==='GT').length,39);
assert.equal(bs.filter(x=>x.testament==='NT').length,27);
assert.equal(new Set(bs.map(x=>x.id)).size,66);
assert.equal(new Set(bs.map(x=>x.title)).size,66);
assert.ok(bs.every(x=>x.reviewStatus==='preliminary'&&x.critical&&x.attributed));
assert.ok(ctx.window.TIDENS_BIBLE_BOOK_RESEARCH.B001.sources.length>=2);
const html=read('index.html');
assert.ok(html.includes('data/bible-books-v857.js')&&html.includes('v857-bible-books.js'));
const data={window:{}};
vm.runInNewContext(read('data/data.generated.js'),data);
assert.equal(vm.runInNewContext('events.length',data),64);
assert.equal(vm.runInNewContext('originalEvents.length',data),129);
vm.runInNewContext(read('data/review-ledger.js'),data);
vm.runInNewContext(read('data/c6-progress.js'),data);
const checks=Object.values(data.window.TIDENS_REVIEW_LEDGER.claimChecks);
assert.equal(checks.reduce((n,x)=>n+x.length,0),35);
assert.equal(data.window.TIDENS_C6_PROGRESS.history.at(-1).claimChecks,35);
console.log('OK V8.57 66 books / 193 existing records / 35 checks');
