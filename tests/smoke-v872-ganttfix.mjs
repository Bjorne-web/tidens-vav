import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8');
const gantt=read('v859-book-gantt.js');
const reader=read('v858-book-reader.js');
const html=read('index.html');
new vm.Script(gantt);
new vm.Script(reader);
assert.ok(gantt.includes("hit.addEventListener('click'"),'Each book row must have its own click handler');
assert.ok(gantt.includes("window.TidensOpenBookV858(b.id)"),'Book click must open common right-side reader');
assert.ok(reader.includes('window.TidensOpenBookV858=openBook'),'Reader entrypoint must be exported');
assert.ok(reader.includes('renderDetail();'),'Selection must render book details');
assert.ok(gantt.includes("plot.style.backgroundImage='none'"),'Remove screen-fixed background stripes');
assert.ok(gantt.includes('Math.ceil(state.min/step)*step'),'Grid coordinates must follow viewport start');
assert.ok(gantt.includes("(year-state.min)/viewSpan*100"),'Grid must pan with visible dates');
assert.ok(gantt.includes('pointer-events:none'),'Guide lines must not intercept book clicks');
assert.ok(gantt.includes('function syncGuideLines()'),'All timeline lanes must update guides');
assert.ok(gantt.includes('renderLane();syncGuideLines()'),'Pan and zoom must repaint calendar guides');
assert.ok(html.includes('Bygge v8.81-gantt-20261015'),'Distinct corrected build ID');
console.log('OK: book opens reader and time guide lines derive from viewport');
