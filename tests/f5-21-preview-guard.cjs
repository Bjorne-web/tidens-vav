'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const project='tidens-vav-f5-review';
const candidate='out/f5-20/site';
const published=fs.readFileSync('index.html','utf8');
assert(!published.includes('f520Review'),'No live review panel allowed');
assert(!published.includes('f5-19-event-open.js'),'No live map adapter allowed');
assert(fs.existsSync(path.join(candidate,'review.html')),'Review entry missing');
assert(fs.existsSync(path.join(candidate,'review-controller.js')),'Review controls missing');
assert(fs.existsSync(path.join(candidate,'out/f5-19/v910-c2-signal-candidate.js')),'Candidate C2 missing');
assert(fs.existsSync(path.join(candidate,'tests/f5-19-event-open.js')),'Candidate gate missing');
assert.notEqual(project,'tidens-vav','Never deploy to production project');
const html=fs.readFileSync(path.join(candidate,'review.html'),'utf8');
assert(html.includes('review-controller.js'),'Review script not mounted');
assert(html.includes('tests/f5-19-event-open.js'),'Map gate not mounted');
assert(html.includes('out/f5-15/c7-undated-articles.js'),'C7 inventory not mounted');
assert(!html.includes('tests/f5-19-probe.js'),'Automated probe must not run for users');
const c7=fs.readFileSync(path.join(candidate,'out/f5-15/c7-undated-articles.js'),'utf8');
assert.equal((c7.match(/c7-undated-reason/g)||[]).length,33,'Expected 33 undated snippets');
console.log('F5.21 staging safety gate OK; project='+project+'; source untouched; 33 C7 records');
