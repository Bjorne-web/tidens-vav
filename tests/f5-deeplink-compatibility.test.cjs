'use strict';
// F5.1 compatibility test evaluates the REAL v835 link parser without running the app.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const {currentLink}=require('./f5-navigation-contract.cjs');
const source=fs.readFileSync('v835-deeplinks.js','utf8');
const app={
 window:{location:{href:'https://tidens-vav.pages.dev/'}},
 document:{readyState:'loading',addEventListener(){}},
 idEvent:id=>['H045','O067'].includes(id)?{id,title:'Tested known real post'}:null,
 renderDetail(){},renderExplore(){},
 URL,URLSearchParams,navigator:{}
};
vm.runInNewContext(source,app,{filename:'v835-deeplinks.js',timeout:2000});
const links=app.window.TidensVavLinks;assert(links);
for(const view of ['explore','timeline','research']){
 const url=currentLink('https://tidens-vav.pages.dev/','H045',view);
 const parsed=links.parse(new URL(url).search);
 assert.equal(parsed.id,'H045');
 assert.equal(parsed.view,view);
 const legacy=links.makeLink('H045',view);
 assert.equal(legacy,url,'F5 contract should produce exactly the URL generated by existing v835 deeplink module');
}
assert.equal(links.parse('?tv_id=topic:good&tv_view=research').error,'unknown-id');
assert.equal(links.parse('?tv_id=H045&tv_view=full').error,'unknown-view');
assert.equal(links.parse('?tv_id=NOT-A-POST&tv_view=timeline').error,'unknown-id');
assert.equal(links.parse('?tv_id=O067&tv_view=timeline').id,'O067');
console.log('F5.1 live legacy deeplink compatibility: PASS (three existing views, canonical ID, unknown topic fails closed)');
